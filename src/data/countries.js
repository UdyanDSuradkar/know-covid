const FIELDS = ["name","iso2","continent","lat","lng","population","cases","deaths","recovered","tests","vaxDoses"];

export const flagOf = (iso2) =>
  (iso2 || "").replace(/./g, (c) => String.fromCodePoint(127397 + c.charCodeAt(0)));

/** Add every derived field the UI reads. Safe to call on live API rows too. */
export function derive(o) {
  const population = o.population || 1;
  return {
    ...o,
    active:   Math.max(0, o.cases - o.deaths - o.recovered),
    casesPM:  (o.cases  / population) * 1e6,
    deathsPM: (o.deaths / population) * 1e6,
    testsPM:  (o.tests  / population) * 1e6,
    cfr:      o.cases ? (o.deaths / o.cases) * 100 : 0,
    vaxPct:   ((o.vaxDoses || 0) / population) * 100,
    flag:     flagOf(o.iso2),
  };
}

export const SNAPSHOT_COUNTRIES = RAW.map((r) => {
  const o = {};
  FIELDS.forEach((f, i) => (o[f] = r[i]));
  return derive(o);
});

